/// A single built-in exercise definition.
class SeedExercise {
  const SeedExercise({
    required this.name,
    required this.category,
    required this.bodyPart,
    required this.equipment,
    required this.difficulty,
    required this.caloriesPerMinute,
    required this.description,
    required this.instructions,
    this.scientificName,
    this.secondaryMuscle,
    this.durationSeconds = 30,
    this.sets = 3,
    this.reps = 12,
    this.restSeconds = 30,
    this.tips = const <String>[],
    this.commonMistakes = const <String>[],
    this.safetyInstructions = const <String>[],
    this.gifPath,
  });

  final String name;
  final ExerciseCategory category;
  final String? scientificName;
  final String bodyPart;
  final String? secondaryMuscle;
  final String equipment;
  final Difficulty difficulty;
  final double caloriesPerMinute;
  final String description;
  final List<String> instructions;

  /// Suggested per-set duration for this exercise, in seconds.
  final int durationSeconds;
  final int sets;
  final int reps;
  final int restSeconds;

  final List<String> tips;
  final List<String> commonMistakes;
  final List<String> safetyInstructions;
  final String? gifPath;

  String get instructionsText => instructions.join('\n');

  String? get tipsText => tips.isEmpty ? null : tips.join('\n');

  String? get mistakesText =>
      commonMistakes.isEmpty ? null : commonMistakes.join('\n');

  String? get safetyText =>
      safetyInstructions.isEmpty ? null : safetyInstructions.join('\n');

  /// Estimated calories for one full pass of the suggested program (kcal).
  int get estimatedCalories {
    final int activeSeconds = sets * durationSeconds;
    final double value = caloriesPerMinute * activeSeconds / 60;
    return value.round().clamp(1, 999);
  }
}

/// One exercise inside a seeded workout routine.
class SeedWorkoutExercise {
  const SeedWorkoutExercise({
    required this.exerciseName,
    this.sets = 0,
    this.reps = 0,
    this.durationSeconds = 0,
    this.restSeconds = 30,
  });

  final String exerciseName;
  final int sets;
  final int reps;
  final int durationSeconds;
  final int restSeconds;
}

